// node Tools/ui-font/build.mjs [--check]
// Deterministic conversion of the upstream BDF to a script-only PugFont/IMGUI atlas.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const dir = path.dirname(fileURLToPath(import.meta.url));
const source = fs.readFileSync(path.join(dir, 'source/Galmuri9.bdf'));
const license = fs.readFileSync(path.join(dir, 'source/OFL.txt'), 'utf8');
const glyphs = [];
for (const block of source.toString('utf8').split('STARTCHAR ').slice(1)) {
  const cp = Number(block.match(/ENCODING (-?\d+)/)[1]);
  // Complete modern Hangul, compatibility jamo, ASCII and the punctuation used by the panel.
  if (!(cp >= 32 && cp <= 126 || cp >= 0x1100 && cp <= 0x11ff ||
        cp >= 0x3130 && cp <= 0x318f || cp >= 0xac00 && cp <= 0xd7a3 ||
        [0xb7,0xd7,0x2013,0x2014,0x2026,0x2190,0x2192,0x25cf].includes(cp))) continue;
  const [w,h,x,y] = block.match(/BBX ([^\r\n]+)/)[1].split(' ').map(Number);
  const advance = Number(block.match(/DWIDTH (\d+)/)[1]);
  const bitmap = block.split('BITMAP')[1].split('ENDCHAR')[0].trim().split(/\r?\n/).filter(Boolean);
  glyphs.push({cp,w,h,x,y,advance,bitmap});
}
glyphs.sort((a,b)=>a.cp-b.cp);
const ascent = Math.max(...glyphs.map(g=>g.y+g.h));
const descent = -Math.min(0,...glyphs.map(g=>g.y));
const height = ascent+descent;
const maxWidth = Math.max(...glyphs.map(g=>Math.max(g.advance,g.x+g.w)));
if(height>16 || maxWidth>16) throw Error(`Unexpected metrics ${height}/${maxWidth}`);
const parts=[];
const header=Buffer.alloc(8);header.writeUInt16LE(glyphs.length,0);header[2]=height;header[3]=descent;
header[4]=maxWidth;header[5]=glyphs.find(g=>g.cp===32).advance;parts.push(header);
for(const g of glyphs) {
  const out=Buffer.alloc(3+height*2);out.writeUInt16LE(g.cp,0);out[2]=g.advance;
  for(let r=0;r<g.h;r++) {
    const bits=BigInt('0x'+g.bitmap[r]);const bitWidth=g.bitmap[r].length*4;
    const dy=descent+g.y+g.h-1-r;
    for(let x=0;x<g.w;x++) if((bits>>BigInt(bitWidth-1-x))&1n) {
      const dx=g.x+x;
      if(dx<0||dx>=g.advance||dy<0||dy>=height) throw Error(`Clipped U+${g.cp.toString(16)} ${dx},${dy}`);
      out.writeUInt16LE(out.readUInt16LE(3+dy*2)|(1<<dx),3+dy*2);
    }
  }
  parts.push(out);
}
const packed=Buffer.concat(parts);const zipped=zlib.gzipSync(packed,{level:9,mtime:0});
const b64=zipped.toString('base64').match(/.{1,120}/g).map(s=>'        "'+s+'"').join(' +\n');
const comment=license.replace(/\*\//g,'* /');
const output=`// Generated by Tools/ui-font/build.mjs. Do not edit the font payload by hand.
// AI Compact Korean: subset/format conversion of Galmuri9, not the upstream font name.
// Source: https://github.com/quiple/galmuri/tree/71e1cacf1437a11220307120e63e30bc275312d4
// BDF SHA256: ${crypto.createHash('sha256').update(source).digest('hex')}
// ${glyphs.length} glyphs, ${height}px cell (${ascent} ascent + ${descent} descent), OFL-1.1.
/*
${comment}
*/
internal static class AICompactFontData
{
    internal const string Packed =
${b64};
}
`;
const target=path.join(dir,'../../Assets/AIPlayerSpike/Scripts/AICompactFontData.cs');
if(process.argv.includes('--check')) {
 if(fs.readFileSync(target,'utf8')!==output) throw Error('Generated font differs; run build.mjs');
} else fs.writeFileSync(target,output);
// Primary text examples must have every glyph, including rare final syllables and standalone jamo.
for(const c of 'Claude ChatGPT Gemini Grok 장비 스킬 채광 달리기 활력 원거리 마법 소환 폭발 훟 힣 ㄱ ㅏ ㅋㅋ …')
 if(c!==' '&&!glyphs.some(g=>g.cp===c.charCodeAt(0))) throw Error(`Missing ${c}`);
console.log(`FONT CHECK OK: ${glyphs.length} glyphs, ${height}px cell, ${zipped.length} compressed bytes, deterministic artifact`);

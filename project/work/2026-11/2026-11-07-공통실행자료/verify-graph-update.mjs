import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
const work='C:/Dev/.head/sessions/코어키퍼-AI-캐릭터/work';
const cwd=path.join(work,'지식그래프');
const out=path.join(work,'2026-11/2026-11-07-공통실행자료');
const b=path.join(work,'2026-11/2026-11-05-지식그래프-개편/B');
const read=p=>JSON.parse(fs.readFileSync(p,'utf8').replace(/^\uFEFF/,''));
const run=args=>execFileSync(process.execPath,args,{cwd,encoding:'utf8',maxBuffer:8*1024*1024});
const check=JSON.parse(run(['tools/product.mjs','check']));
fs.writeFileSync(path.join(out,'graph-check.json'),JSON.stringify(check,null,2)+'\n');
if(!check.ok||check.stale.length||check.structuralErrors.length||check.baselineDrift.warning)throw Error('Graph check failed');
const deterministic=run(['tools/product-build.mjs','--check']);
const commands=[['intent','P.original-request'],['show','R.stop-action'],['show','R.finish-goal'],['show','R.request-plan'],['source','R.common-offline'],['policy','pol.ai-action-control']];
let queries='';
for(const args of commands)queries+='\n$ node tools/product.mjs '+args.join(' ')+'\n'+run(['tools/product.mjs',...args]);
queries+='\n$ node tools/query.mjs why F.common-execution\n'+run(['tools/query.mjs','why','F.common-execution']);
fs.writeFileSync(path.join(out,'graph-queries.txt'),queries);
const sample=read(path.join(b,'validation-review.json'));
const g=read(path.join(b,'code.graph.json'));
const byId=new Map(g.nodes.map(n=>[n.id,n]));
const samples=sample.samples.flatMap(s=>s.handlers.map(h=>{
 const n=byId.get(h.to);
 return {id:h.to,exists:!!n,previousLine:h.line,currentLine:n?.lineStart,sameLine:h.line===n?.lineStart};
}));
fs.writeFileSync(path.join(out,'graph-sample-check.json'),JSON.stringify({sourceCommit:g.meta.sourceCommit,samples},null,2)+'\n');
if(samples.some(s=>!s.exists))throw Error('Existing reviewed sample symbol missing');
const product=path.join(work,'2026-11/2026-11-05-지식그래프-실화면/D/graph.json');
const paths=[product,path.join(cwd,'graph/graph.json'),path.join(b,'code.graph.json'),path.join(work,'2026-11/2026-11-07-기획연결/graph.json')];
const hashes=Object.fromEntries(paths.map(p=>[p,crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex')]));
fs.writeFileSync(path.join(out,'graph-final-hashes.json'),JSON.stringify(hashes,null,2)+'\n');
console.log(JSON.stringify({ok:true,baseline:check.baselineDrift.baseline,byteIdentical:deterministic.trim(),sampleCount:samples.length,sampleLineChanges:samples.filter(s=>!s.sameLine).length,snapshot:read(path.join(b,'snapshot-verification.json')).fileCount,codeDeterminism:read(path.join(b,'determinism.json')).equal}));

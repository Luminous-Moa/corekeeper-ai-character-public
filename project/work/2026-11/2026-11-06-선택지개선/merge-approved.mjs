import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const task=path.dirname(fileURLToPath(import.meta.url)),repo='C:/Dev/CoreKeeperModSDK';
const base='902721ec505df42d74d0b2d245ed34a049faadad',target='b25099f6fd31e4c4c3618357eb9e8101e0e17124';
const out=task+'/evidence/merge';
if(fs.existsSync(out))throw Error('Merge evidence already exists; inspect instead of overwrite.');
fs.mkdirSync(out,{recursive:true});
const git=(...args)=>execFileSync('git',['-C',repo,...args],{encoding:'utf8'});
const hash=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
function local(){const files=git('ls-files','-m','--others','--exclude-standard','-z').split('\0').filter(Boolean);
 return {head:git('rev-parse','HEAD').trim(),branch:git('branch','--show-current').trim(),status:git('status','--short','--branch'),index:git('diff','--cached','--name-status'),files:files.map(p=>({path:p,sha256:hash(repo+'/'+p)}))};}
const before=local();fs.writeFileSync(out+'/before.json',JSON.stringify(before,null,2)+'\n');
if(before.head!==base||before.branch!=='ai-character'||before.index.trim())throw Error('Unexpected HEAD, branch, or staged changes.');
if(git('rev-parse','choice-fixes-20261106').trim()!==target)throw Error('Candidate branch differs from approval.');
git('merge-base','--is-ancestor',base,target);
const changed=git('diff','--name-only',base,target).trim().split('\n');
if(before.files.some(f=>changed.includes(f.path)))throw Error('Dirty files overlap approved merge.');
const canonical=JSON.parse(fs.readFileSync(task+'/graph-stage-b25099f/canonical-before.json','utf8'));
const graphChanged=canonical.filter(f=>hash(f.path)!==f.sha256);
fs.writeFileSync(out+'/canonical-precheck.json',JSON.stringify({files:canonical.length,changed:graphChanged},null,2)+'\n');
if(graphChanged.length)throw Error('Canonical graph changed concurrently; no merge or overwrite performed.');
const merged=git('merge','--ff-only',target);fs.writeFileSync(out+'/git-merge.txt',merged);
const after=local();fs.writeFileSync(out+'/after.json',JSON.stringify(after,null,2)+'\n');
const changedLocal=before.files.filter(f=>!fs.existsSync(repo+'/'+f.path)||hash(repo+'/'+f.path)!==f.sha256);
const result={head:after.head,branch:after.branch,fastForward:after.head===target,changedFiles:changed,localFilesChecked:before.files.length,localChanged:changedLocal,index:after.index};
fs.writeFileSync(out+'/result.json',JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
if(after.head!==target||changedLocal.length||after.index.trim())throw Error('Post-merge preservation check failed.');

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const T=path.dirname(fileURLToPath(import.meta.url)),W='C:/Dev/.head/sessions/코어키퍼-AI-캐릭터/work';
const repo='C:/Dev/CoreKeeperModSDK',sha='b25099f6fd31e4c4c3618357eb9e8101e0e17124';
const P=W+'/2026-11/2026-11-05-지식그래프-개편',L=W+'/2026-11/2026-11-05-지식그래프-실화면',G=W+'/지식그래프';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8').replace(/^\uFEFF/,''));
const hash=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const git=(...a)=>execFileSync('git',['-C',repo,...a],{encoding:'utf8'}).trim();
const before=read(T+'/evidence/merge/before.json'),commands=read(T+'/evidence/merge/graph-commands.json');
const changed=before.files.filter(f=>!fs.existsSync(repo+'/'+f.path)||hash(repo+'/'+f.path)!==f.sha256);
const report={head:git('rev-parse','HEAD'),branch:git('branch','--show-current'),index:git('diff','--cached','--name-only'),localFilesChecked:before.files.length,localChanged:changed,status:git('status','--short','--branch')};
if(report.head!==sha||report.branch!=='ai-character'||report.index||changed.length)throw Error('Final repository preservation failed: '+JSON.stringify(report));
const deterministic=T+'/graph-stage-b25099f/work/2026-11/2026-11-05-지식그래프-개편/B/determinism.json';
const proof=read(deterministic);
report.extractionMatchesReviewedStage=Object.fromEntries(Object.entries(proof.second).map(([f,h])=>[f,hash(P+'/B/'+f)===h]));
if(Object.values(report.extractionMatchesReviewedStage).some(v=>!v))throw Error('Official extraction differs from reviewed stage');
// The proof is transferable only after every official extracted byte matches its two reviewed runs.
fs.copyFileSync(deterministic,P+'/B/determinism.json');
report.determinismProof='Reviewed stage two-run proof reused after all seven official outputs match exactly';
const saved=read(T+'/evidence/merge/graph-before/manifest.json');
report.pastObservationSources=saved.filter(f=>/observations\.json$/.test(f.path)).map(f=>({path:f.path,unchanged:hash(f.path)===f.sha256}));
if(report.pastObservationSources.some(f=>!f.unchanged))throw Error('Past observation changed');
const check=JSON.parse(commands.find(c=>c.label==='product check').stdout);
report.baselineDrift=check.baselineDrift;
report.historicalRuntime=check.validation.supplementalRuntime;
if(report.historicalRuntime.sameRevision||report.historicalRuntime.evidenceAppliesToCurrentRevision)throw Error('Historical evidence promoted');
const graph=read(G+'/graph/graph.json');
report.development={nodes:graph.nodes.length,edges:graph.edges.length};
report.choiceOutput=commands.find(c=>c.label==='CHOICE on merged source').stdout;
report.productOutput=commands.find(c=>c.label==='product build').stdout.trim();
report.sourceFiles=read(T+'/evidence/merge/applied-graph-sources.json').files;
report.regeneratedChanged=saved.filter(f=>!fs.existsSync(f.path)||hash(f.path)!==f.sha256).map(f=>f.path);
report.observationLink=read(L+'/C/overlay-source.json').evidenceReferences.filter(x=>x.includes('선택지개선'));
fs.writeFileSync(T+'/evidence/merge/final-verification.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({head:report.head,localFilesChecked:report.localFilesChecked,localChanged:changed.length,development:report.development,product:report.productOutput,choice:report.choiceOutput,extractionMatchesReviewedStage:report.extractionMatchesReviewedStage,baselineDrift:report.baselineDrift,observationFilesPreserved:report.pastObservationSources.length,changedCanonicalFiles:report.regeneratedChanged.length},null,2));
